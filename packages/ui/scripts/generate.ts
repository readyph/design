/**
 * Token generator. After the RDY-244 reset there are no tokens yet; this emits an
 * empty theme.css and an empty Tailwind preset so the package builds and consumers
 * keep resolving `@readyph/ui/preset` and `@readyph/ui/theme.css`.
 * Run with:  npm run generate  (tsx scripts/generate.ts)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

writeFileSync(
  resolve(pkgRoot, 'src/styles/theme.css'),
  `/* ReadyPH design tokens. GENERATED by scripts/generate.ts. Empty after the RDY-244 reset. */\n:root {\n}\n`,
);

const preset = { darkMode: ['class', '[data-theme="dark"]'], theme: { extend: {} } };
writeFileSync(
  resolve(pkgRoot, 'preset.cjs'),
  `/**\n * ReadyPH Tailwind preset. GENERATED by scripts/generate.ts. Empty after the RDY-244 reset.\n */\n/** @type {import('tailwindcss').Config} */\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`,
);
