/**
 * Token generator (RDY-246). Reads src/tokens/* and writes:
 *   src/styles/theme.css    light :root tokens + non-colour tokens + responsive overrides
 *   src/styles/globals.css  theme import, Tailwind layers, the dark blocks, base styles
 *   preset.cjs              Tailwind preset mapping utilities to the CSS variables
 * Tokens are global (never scoped to a page). `data-theme="light|dark"` on <html>; absent = system.
 * Run with:  npm run generate  (tsx scripts/generate.ts)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { surfaces, status, dataviz, identity, leda, type Pair } from '../src/tokens/colors';
import { fonts, type, radius, spacing, layout, responsive, shadow, blur, motion } from '../src/tokens/scale';

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const colorGroups: Record<string, Pair>[] = [surfaces, status, dataviz, leda];
const allColors: Record<string, Pair> = Object.assign({}, ...colorGroups);

const decl = (pairs: [string, string][], indent: string) => pairs.map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');
const lightVars = (): [string, string][] => [
  ...Object.entries(allColors).map(([k, v]) => [k, v[0]] as [string, string]),
  ...identity.map((c, i) => [`identity-${i + 1}`, c] as [string, string]),
  ...Object.entries(shadow).map(([k, v]) => [k, v[0]] as [string, string]),
];
const darkVars = (): [string, string][] => [
  ...Object.entries(allColors).filter(([, v]) => v[0] !== v[1]).map(([k, v]) => [k, v[1]] as [string, string]),
  ...Object.entries(shadow).map(([k, v]) => [k, v[1]] as [string, string]),
];
const typeVars = (): [string, string][] =>
  Object.entries(type).flatMap(([k, [size, lh, weight, ls]]) => [
    [`fs-${k}`, size], [`lh-${k}`, lh], ...(weight ? [[`fw-${k}`, weight]] : []), ...(ls ? [[`ls-${k}`, ls]] : []),
  ] as [string, string][]);

const theme = `/* ReadyPH design tokens (RDY-246). GENERATED by scripts/generate.ts from src/tokens/*. Global: not scoped to any page. */
:root {
  color-scheme: light dark;
${decl(lightVars(), '  ')}
${decl([['font', fonts.font], ['mono', fonts.mono]], '  ')}
${decl(typeVars(), '  ')}
${decl(Object.entries(radius).map(([k, v]) => [`r-${k}`, v] as [string, string]), '  ')}
${decl(Object.entries(spacing), '  ')}
${decl(Object.entries(layout), '  ')}
${decl(Object.entries(blur), '  ')}
${decl(Object.entries(motion), '  ')}
}
${responsive.map((r) => `@media ${r.query} {\n  :root {\n${decl(Object.entries(r.vars), '    ')}\n  }\n}`).join('\n')}
`;
writeFileSync(resolve(pkgRoot, 'src/styles/theme.css'), theme);

const dark = decl(darkVars(), '    ');
const darkExplicit = decl(darkVars(), '  ');
const globals = `/* GENERATED by scripts/generate.ts (RDY-246). Do not edit; change src/tokens/* instead. */
@import url('https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans:wght@400;500;600&display=swap');
@import './theme.css';

@tailwind base;
@tailwind components;
@tailwind utilities;

/* Dark: follows the system unless html[data-theme="light"]; html[data-theme="dark"] forces it. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${dark}
  }
}
:root[data-theme="light"] { color-scheme: light; }
:root[data-theme="dark"] {
  color-scheme: dark;
${darkExplicit}
}

@layer base {
  /* html stays at the browser default (16px) so Tailwind's rem scale is px-accurate (h-8 = 32px); the 14px body text size lives on body (RDY-303). */
  html { font-size: 100%; background: var(--frame); -webkit-font-smoothing: antialiased; }
  body { margin: 0; font-family: var(--font); font-size: var(--fs-body); line-height: var(--lh-body); background: var(--frame); color: var(--text); font-variant-numeric: tabular-nums; }
  /* Content drawn straight on --frame (the place column) gets the frame-specific row rule; set data-surface="frame" on its root. */
  [data-surface="frame"] { --rule: var(--frame-rule); }
  :focus-visible { outline: 2px solid var(--accent); outline-offset: 2px; }
  code, kbd, samp { font-family: var(--mono); font-size: 13px; }
  /* Reduced motion is handled per component (spec 4.7 keeps the 140ms fade and the halo opacity fade). */
}
`;
writeFileSync(resolve(pkgRoot, 'src/styles/globals.css'), globals);

const v = (k: string) => `var(--${k})`;
const colors: Record<string, string | Record<string, string>> = {};
for (const k of Object.keys(surfaces)) colors[k] = v(k);
for (const tone of ['ok', 'warn', 'bad', 'info']) {
  colors[tone] = {
    DEFAULT: v(tone), bg: v(`${tone}-bg`), ink: v(`${tone}-ink`), ...(`${tone}-on` in status ? { on: v(`${tone}-on`) } : {}), ...(tone !== 'info' ? { dot: v(`${tone}-dot`) } : {}),
  };
}
for (const k of Object.keys(dataviz)) colors[k] = v(k);
identity.forEach((_, i) => (colors[`identity-${i + 1}`] = v(`identity-${i + 1}`)));
for (const k of Object.keys(leda)) colors[k] = v(k);

const fontSize = Object.fromEntries(
  Object.entries(type).map(([k, [, , w, ls]]) => [
    k, [v(`fs-${k}`), { lineHeight: v(`lh-${k}`), ...(w ? { fontWeight: v(`fw-${k}`) } : {}), ...(ls ? { letterSpacing: v(`ls-${k}`) } : {}) }],
  ]),
);
const preset = {
  darkMode: ['variant', [
    '@media (prefers-color-scheme: dark) { &:not([data-theme="light"], [data-theme="light"] *) }',
    '&:is([data-theme="dark"], [data-theme="dark"] *)',
  ]],
  theme: {
    extend: {
      colors,
      fontFamily: { sans: [v('font')], mono: [v('mono')] },
      fontSize,
      borderRadius: Object.fromEntries(Object.keys(radius).map((k) => [k, v(`r-${k}`)])),
      spacing: Object.fromEntries(Object.keys(spacing).map((k) => [k, v(k)])),
      width: { rail: v('rail'), place: v('place'), 'leda-w': v('leda-w') },
      height: { status: v('status'), 'map-h': v('map-h'), 'sheet-bar': v('sheet-bar') },
      boxShadow: { float: v('shadow-float') },
      keyframes: {
        'row-flash': { '0%, 40%': { backgroundColor: v('accent-tint') }, '100%': { backgroundColor: 'transparent' } },
        'tab-fade': { from: { opacity: '0' }, to: { opacity: '1' } },
        // C15 subpage lanes (spec 4.7). in = new pane enters from its side; the old one drifts 6% the other way and dims. out = reverse.
        'sub-in-r': { from: { transform: 'translateX(100%)' }, to: { transform: 'translateX(0)' } },
        'sub-in-l': { from: { transform: 'translateX(-100%)' }, to: { transform: 'translateX(0)' } },
        'sub-out-r': { from: { transform: 'translateX(0)' }, to: { transform: 'translateX(100%)' } },
        'sub-out-l': { from: { transform: 'translateX(0)' }, to: { transform: 'translateX(-100%)' } },
        'sub-drift-l': { from: { transform: 'translateX(0)', opacity: '1' }, to: { transform: 'translateX(calc(-1 * var(--subpage-drift)))', opacity: v('subpage-dim') } },
        'sub-drift-r': { from: { transform: 'translateX(0)', opacity: '1' }, to: { transform: 'translateX(var(--subpage-drift))', opacity: v('subpage-dim') } },
        'sub-back-l': { from: { transform: 'translateX(calc(-1 * var(--subpage-drift)))', opacity: v('subpage-dim') }, to: { transform: 'translateX(0)', opacity: '1' } },
        'sub-back-r': { from: { transform: 'translateX(var(--subpage-drift))', opacity: v('subpage-dim') }, to: { transform: 'translateX(0)', opacity: '1' } },
        'sub-fade': { from: { opacity: '0' }, to: { opacity: '1' } },
      },
      animation: {
        'row-flash': 'row-flash var(--dur-row-flash) ease-out 1',
        'tab-fade': 'tab-fade var(--dur-tab) linear',
        'sub-in-r': 'sub-in-r var(--dur-subpage-in) var(--ease-subpage) backwards',
        'sub-in-l': 'sub-in-l var(--dur-subpage-in) var(--ease-subpage) backwards',
        'sub-out-r': 'sub-out-r var(--dur-subpage-out) var(--ease-subpage) forwards',
        'sub-out-l': 'sub-out-l var(--dur-subpage-out) var(--ease-subpage) forwards',
        'sub-drift-l': 'sub-drift-l var(--dur-subpage-in) var(--ease-subpage) forwards',
        'sub-drift-r': 'sub-drift-r var(--dur-subpage-in) var(--ease-subpage) forwards',
        'sub-back-l': 'sub-back-l var(--dur-subpage-out) var(--ease-subpage) backwards',
        'sub-back-r': 'sub-back-r var(--dur-subpage-out) var(--ease-subpage) backwards',
        'sub-fade': 'sub-fade var(--dur-reduced-fade) linear backwards',
      },
      transitionTimingFunction: { subpage: v('ease-subpage'), halo: v('ease-halo') },
      transitionDuration: { hover: v('dur-hover'), 'hover-slow': v('dur-hover-slow'), tab: v('dur-tab'), 'subpage-in': v('dur-subpage-in'), 'subpage-out': v('dur-subpage-out') },
    },
  },
};
writeFileSync(
  resolve(pkgRoot, 'preset.cjs'),
  `/**\n * ReadyPH Tailwind preset. GENERATED by scripts/generate.ts (RDY-246).\n */\n/** @type {import('tailwindcss').Config} */\nconst preset = ${JSON.stringify(preset, null, 2)};\npreset.plugins = [require('./plugins/container-queries.cjs')];\nmodule.exports = preset;\n`,
);
